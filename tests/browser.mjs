import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
const browser = await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:2,hasTouch:true,isMobile:true});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const state=()=>page.evaluate(()=>window.__precision());
await page.goto('http://127.0.0.1:5173/?stage=prototype');await page.waitForSelector('canvas');
assert.equal(await page.locator('#developer').isVisible(),false);
await page.getByRole('button',{name:'スタート',exact:true}).click();
await page.keyboard.down('ArrowUp');await page.waitForTimeout(250);await page.keyboard.up('ArrowUp');
assert.ok((await state()).position.y<1550);
await page.waitForTimeout(50);const stopped=(await state()).position.y;await page.waitForTimeout(100);assert.equal((await state()).position.y,stopped);
const box=await page.locator('#stick').boundingBox();
await page.mouse.move(box.x+box.width/2,box.y+box.height/2);await page.mouse.down();await page.mouse.move(box.x+box.width/2,box.y+box.height/2-15);await page.waitForTimeout(150);await page.mouse.up();
await page.waitForTimeout(50);const released=(await state()).position.y;await page.waitForTimeout(100);assert.equal((await state()).position.y,released);
const cdp=await page.context().newCDPSession(page);
const touchX=box.x+box.width/2,touchY=box.y+box.height/2;
const beforeTouch=(await state()).position.y;
await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:touchX,y:touchY}]});
await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:touchX,y:touchY-40}]});
await page.waitForTimeout(150);
await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
await page.waitForTimeout(40);const touchStopped=(await state()).position.y;
assert.ok(touchStopped<beforeTouch);await page.waitForTimeout(100);assert.equal((await state()).position.y,touchStopped);
await page.getByRole('button',{name:'練習',exact:true}).click();await page.selectOption('#mode','practice');await page.selectOption('#checkpoint','windmill');await page.uncheck('#timed');await page.getByRole('button',{name:'適用',exact:true}).click();
assert.deepEqual((await state()).position,{x:645,y:820});assert.equal((await state()).settings.timed,false);
await page.getByRole('button',{name:'スタート',exact:true}).click();
await page.screenshot({path:'tests/mobile.png'});
await page.goto('http://127.0.0.1:5173/?dev=1&stage=prototype');await page.waitForSelector('canvas');
await page.getByRole('button',{name:'練習',exact:true}).click();assert.equal(await page.locator('#developer').isVisible(),true);
await page.selectOption('#checkpoint','press');await page.fill('#elapsed','20');await page.check('#invincible');await page.check('#hitboxes');await page.fill('#obstacleSpeed','2');await page.getByRole('button',{name:'適用',exact:true}).click();
assert.equal((await state()).time,20);assert.deepEqual((await state()).position,{x:1100,y:710});
await page.getByRole('button',{name:'スタート',exact:true}).click();await page.waitForTimeout(100);assert.ok((await state()).time>20);
await page.screenshot({path:'tests/developer.png'});
for(const [width,height] of [[320,568],[430,932],[1440,900]]){await page.setViewportSize({width,height});await page.waitForTimeout(80);assert.ok(await page.locator('#stick').isVisible());assert.ok(await page.locator('#retry').isVisible());const fits=await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth);assert.ok(fits);}
assert.deepEqual(errors,[]);console.log('PASS: browser movement, release, touch input, joystick, practice, developer settings, 4 viewport sizes; no page errors');
await browser.close();
